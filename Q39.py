"""Assignment 1 - Question 39: Demonstrate the use of type() with string, list, tuple and dictionary variables."""

text = "Hello"
numbers_list = [1, 2, 3]
numbers_tuple = (4, 5, 6)
info_dict = {"key": "value"}

print("type(text):", type(text))
print("type(numbers_list):", type(numbers_list))
print("type(numbers_tuple):", type(numbers_tuple))
print("type(info_dict):", type(info_dict))
