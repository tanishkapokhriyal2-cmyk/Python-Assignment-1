"""Assignment 1 - Question 28: Demonstrate the use of abs(), round() and pow() functions."""

negative_num = -18.678
decimal_num = 3.14159

print("abs(-18.678) =", abs(negative_num))
print("round(3.14159, 2) =", round(decimal_num, 2))
print("round(3.14159) =", round(decimal_num))
print("pow(2, 5) =", pow(2, 5))
