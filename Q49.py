"""Assignment 1 - Question 49: Demonstrate the difference between integer and floating-point values."""

int_val = 7
float_val = 7.0

print("Integer value:", int_val, "| Type:", type(int_val))
print("Floating-point value:", float_val, "| Type:", type(float_val))
print("Integer division 7 // 2 =", 7 // 2, "| Type:", type(7 // 2))
print("Float division 7 / 2 =", 7 / 2, "| Type:", type(7 / 2))
