"""Assignment 1 - Question 22: Display the data type of different variables using type()."""

num = 100
price = 49.99
city = "Mumbai"
is_active = False
items = [1, 2, 3]

print("Type of num:", type(num))
print("Type of price:", type(price))
print("Type of city:", type(city))
print("Type of is_active:", type(is_active))
print("Type of items:", type(items))
