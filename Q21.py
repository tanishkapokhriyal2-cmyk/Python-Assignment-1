"""Assignment 1 - Question 21: Demonstrate integer, float, complex, string and Boolean data types."""

int_val = 42
float_val = 3.14
complex_val = 2 + 5j
string_val = "Python"
bool_val = True

print("Integer value:", int_val, "| Type:", type(int_val))
print("Float value:", float_val, "| Type:", type(float_val))
print("Complex value:", complex_val, "| Type:", type(complex_val))
print("String value:", string_val, "| Type:", type(string_val))
print("Boolean value:", bool_val, "| Type:", type(bool_val))
