"""Assignment 1 - Question 38: Display the length of a string, list, tuple and dictionary using len()."""

sample_str = "Python"
sample_list = [10, 20, 30, 40]
sample_tuple = ("a", "b", "c")
sample_dict = {"x": 1, "y": 2, "z": 3, "w": 4, "v": 5}

print("Length of string:", len(sample_str))
print("Length of list:", len(sample_list))
print("Length of tuple:", len(sample_tuple))
print("Length of dictionary:", len(sample_dict))
