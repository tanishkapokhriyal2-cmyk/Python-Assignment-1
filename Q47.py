"""Assignment 1 - Question 47: Demonstrate the use of list(), tuple() and dict() constructors."""

created_list = list((10, 20, 30))
created_tuple = tuple([40, 50, 60])
created_dict = dict(name="Ananya", branch="IT", year=2)

print("List created with list():", created_list)
print("Tuple created with tuple():", created_tuple)
print("Dictionary created with dict():", created_dict)
